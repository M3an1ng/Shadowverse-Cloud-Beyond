namespace ShadowverseBeyond.Server.Domain.Events.ActionRequests
{
    /// <summary>
    /// Represents a player's request to play a card.
    /// This event is generated by the initial action processing step
    /// and triggers the core logic (PP check, summoning/spell effect) within the event loop.
    /// </summary>
    // Change from record to class to inherit from GameEventBase (class)
    public class PlayCardRequestedEvent : GameEventBase
    {
        // Define properties explicitly since it's a class now
        public Guid PlayerId { get; }
        public PlayCardActionDto ActionDto { get; }

        // Properties required by IGameEvent (partially handled by GameEventBase)
        // GameEventBase handles EventId, Timestamp, EventType
        // We need to decide how to populate SourcePlayer, SourceCard, Parameters if needed for this specific event.
        // For a request event, these might often be null or determined during processing.
        // Let's initialize them simply for now.
        // Constructor to initialize properties and call base constructor
        public PlayCardRequestedEvent(Guid playerId, PlayCardActionDto actionDto)
            : base(EventType.PlayCardRequested) // Call base constructor with event type
        {
            PlayerId = playerId;
            ActionDto = actionDto;
        }

        // The core logic for playing a card (PP deduction, summoning, spell effects)
        // will be handled by the IEventProcessor when it processes this event.
        // Therefore, the ExecuteAsync here should return an empty list of subsequent events.

        // This internal domain event likely doesn't need a direct DTO representation for broadcasting.
        // Return null or throw if conversion is attempted unexpectedly.
        public GameEventDto? ToDto(IMapper mapper)
        {
            _logger.LogWarning("Attempted to convert PlayCardRequestedEvent to DTO. This event type is typically not broadcast.");
            return null; // Indicate no DTO representation is available/needed.
        }

        // Add logger for ExecuteAsync debug message
        // Using a simple console logger factory for now. Consider injecting ILogger properly later.
        private static readonly ILogger _logger = LoggerFactory.Create(builder => builder.AddConsole()).CreateLogger<PlayCardRequestedEvent>();
    }
}