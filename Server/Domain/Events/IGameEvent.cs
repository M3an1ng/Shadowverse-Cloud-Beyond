using ShadowverseBeyond.Server.Domain.Entities;
using ShadowverseBeyond.Server.Dtos;
using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;

namespace ShadowverseBeyond.Server.Domain.Events
{
    /// <summary>
    /// Base interface for all game events in the Event-driven ability system.
    /// Events represent atomic game actions that can trigger abilities.
    /// </summary>
    public interface IGameEvent
    {
        /// <summary>
        /// Unique identifier for this event type (e.g., "play_card", "damage", "summon").
        /// </summary>
        string EventType { get; }

        /// <summary>
        /// Unique identifier for this specific event instance.
        /// </summary>
        int EventId { get; }

        /// <summary>
        /// Timestamp when the event was created.
        /// </summary>
        DateTime Timestamp { get; }

        /// <summary>
        /// The player who initiated this event (if applicable).
        /// </summary>
        PlayerStateDto? SourcePlayer { get; }

        /// <summary>
        /// The card instance that is the source of this event (if applicable).
        /// </summary>
        CardInstance? SourceCard { get; }

        /// <summary>
        /// Additional parameters specific to this event type.
        /// </summary>
        Dictionary<string, object> Parameters { get; }

        /// <summary>
        /// Executes the event's core logic and returns any new events that should be triggered.
        /// This method should modify game state and return subsequent events.
        /// </summary>
        /// <param name="context">The current game context.</param>
        /// <returns>A list of new events generated by executing this event.</returns>
        Task<List<IGameEvent>> ExecuteAsync(GameContext context);
    }

    /// <summary>
    /// Base abstract class for game events providing common functionality.
    /// </summary>
    public abstract class GameEventBase : IGameEvent
    {
        private static int _nextEventId = 1;

        public string EventType { get; protected set; } = string.Empty;
        public int EventId { get; protected set; }
        public DateTime Timestamp { get; protected set; } = DateTime.UtcNow;
        public PlayerStateDto? SourcePlayer { get; set; }
        public CardInstance? SourceCard { get; set; }
        public Dictionary<string, object> Parameters { get; set; } = new();

        protected GameEventBase(string eventType)
        {
            EventType = eventType;
            EventId = Interlocked.Increment(ref _nextEventId);
        }

        public abstract Task<List<IGameEvent>> ExecuteAsync(GameContext context);
    }
}
