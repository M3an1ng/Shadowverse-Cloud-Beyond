using ShadowverseBeyond.Server.Domain.Entities;
using ShadowverseBeyond.Server.Domain.Events;
using System.Collections.Generic;
using System.Threading.Tasks;

namespace ShadowverseBeyond.Server.Domain.Abilities
{
    /// <summary>
    /// Interface for all card abilities in the game.
    /// Abilities listen to specific game events and can trigger effects in response.
    /// </summary>
    public interface ICardAbility
    {
        /// <summary>
        /// The tag/identifier for this ability type (e.g., "Fanfare", "LastWords", "Rush").
        /// </summary>
        string AbilityTag { get; }

        /// <summary>
        /// List of event types this ability listens to (e.g., "play_card", "summon", "card_destroyed").
        /// </summary>
        List<string> TriggerEvents { get; }

        /// <summary>
        /// The card instance that owns this ability.
        /// </summary>
        CardInstance SourceCard { get; }

        /// <summary>
        /// Determines if this ability should trigger in response to the given event.
        /// </summary>
        /// <param name="triggerEvent">The event that might trigger this ability.</param>
        /// <param name="context">The current game context.</param>
        /// <returns>True if the ability should trigger, false otherwise.</returns>
        Task<bool> ShouldTriggerAsync(IGameEvent triggerEvent, GameContext context);

        /// <summary>
        /// Executes the ability's effect when triggered, returning any new events to be processed.
        /// </summary>
        /// <param name="triggerEvent">The event that triggered this ability.</param>
        /// <param name="context">The current game context.</param>
        /// <returns>A list of new events generated by this ability.</returns>
        Task<List<IGameEvent>> OnTriggeredAsync(IGameEvent triggerEvent, GameContext context);
    }

    /// <summary>
    /// Base abstract class for card abilities providing common functionality.
    /// </summary>
    public abstract class CardAbilityBase : ICardAbility
    {
        public string AbilityTag { get; protected set; } = string.Empty;
        public List<string> TriggerEvents { get; protected set; } = new();
        public CardInstance SourceCard { get; set; } = null!;

        protected CardAbilityBase(string abilityTag, List<string> triggerEvents)
        {
            AbilityTag = abilityTag;
            TriggerEvents = triggerEvents;
        }

        public abstract Task<bool> ShouldTriggerAsync(IGameEvent triggerEvent, GameContext context);
        public abstract Task<List<IGameEvent>> OnTriggeredAsync(IGameEvent triggerEvent, GameContext context);

        /// <summary>
        /// Helper method to create an AbilityTriggeredEvent for broadcasting.
        /// </summary>
        /// <param name="triggerEvent">The event that triggered this ability.</param>
        /// <param name="parameters">Additional parameters for the ability trigger.</param>
        /// <returns>An AbilityTriggeredEvent instance.</returns>
        protected AbilityTriggeredEvent CreateAbilityTriggeredEvent(
            IGameEvent triggerEvent, 
            Dictionary<string, object>? parameters = null)
        {
            return new AbilityTriggeredEvent(SourceCard, AbilityTag, triggerEvent, parameters);
        }
    }

    /// <summary>
    /// Event generated when an ability is triggered, used for broadcasting and ability interactions.
    /// </summary>
    public class AbilityTriggeredEvent : GameEventBase
    {
        public AbilityTriggeredEvent(
            CardInstance sourceCard, 
            string abilityTag, 
            IGameEvent triggerEvent,
            Dictionary<string, object>? abilityParameters = null)
            : base("ability_triggered")
        {
            SourceCard = sourceCard;
            Parameters["ability_tag"] = abilityTag;
            Parameters["trigger_event"] = triggerEvent;
            Parameters["ability_parameters"] = abilityParameters ?? new Dictionary<string, object>();
        }

        public override async Task<List<IGameEvent>> ExecuteAsync(GameContext context)
        {
            // This event is primarily for broadcasting and doesn't execute game logic itself
            // Other abilities can listen to this event to respond to specific ability tags
            return await Task.FromResult(new List<IGameEvent>());
        }
    }
}
