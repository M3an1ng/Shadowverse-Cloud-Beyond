        private static List<double> ResolveWeights(
            EffectConfig effectConfig,
            string key,
            int optionCount,
            GameContext context,
            IValueSourceResolver resolver)
        {
            if (!TryResolveParameterValue(effectConfig, key, context, resolver, out var resolved))
            {
                return Enumerable.Repeat(1d, optionCount).ToList();
            }

            var weights = CoerceToDoubleList(resolved);
            if (weights.Count == 0)
            {
                return Enumerable.Repeat(1d, optionCount).ToList();
            }

            var normalized = new List<double>(optionCount);
            for (var i = 0; i < optionCount; i++)
            {
                var weight = i < weights.Count ? weights[i] : 1d;
                normalized.Add(weight < 0 ? 0 : weight);
            }

            if (normalized.All(value => value <= 0))
            {
                return Enumerable.Repeat(1d, optionCount).ToList();
            }

            return normalized;
        }

        private static bool TryResolveParameterValue(
            EffectConfig effectConfig,
            string key,
            GameContext context,
            IValueSourceResolver resolver,
            out object? resolved)
        {
            resolved = null;
            if (effectConfig.Parameters == null || effectConfig.Parameters.Count == 0)
            {
                return false;
            }

            if (!TryGetParameter(effectConfig.Parameters, key, out var value))
            {
                return false;
            }

            if (value == null)
            {
                return false;
            }

            resolved = value.Resolve(context, resolver);
            return true;
        }

        private static bool TryGetParameter(
            Dictionary<string, ValueConfig> parameters,
            string key,
            out ValueConfig value)
        {
            if (parameters.TryGetValue(key, out value!))
            {
                return true;
            }

            foreach (var entry in parameters)
            {
                if (string.Equals(entry.Key, key, StringComparison.OrdinalIgnoreCase))
                {
                    value = entry.Value;
                    return true;
                }
            }

            value = null!;
            return false;
        }

        private static bool CoerceToBool(object? value, bool fallback)
        {
            switch (value)
            {
                case null:
                    return fallback;
                case bool b:
                    return b;
                case int i:
                    return i != 0;
                case long l:
                    return l != 0;
                case double d:
                    return Math.Abs(d) > double.Epsilon;
                case float f:
                    return Math.Abs(f) > float.Epsilon;
                case decimal m:
                    return m != 0;
                case string s when bool.TryParse(s, out var parsed):
                    return parsed;
                case string s when int.TryParse(s, out var intParsed):
                    return intParsed != 0;
                case JsonElement jsonElement:
                    if (jsonElement.ValueKind == JsonValueKind.True) return true;
                    if (jsonElement.ValueKind == JsonValueKind.False) return false;
                    if (jsonElement.ValueKind == JsonValueKind.Number && jsonElement.TryGetInt32(out var number))
                    {
                        return number != 0;
                    }
                    if (jsonElement.ValueKind == JsonValueKind.String && bool.TryParse(jsonElement.GetString(), out var jsonBool))
                    {
                        return jsonBool;
                    }
                    return fallback;
                default:
                    return fallback;
            }
        }

        private static SequenceOrder CoerceToSequenceOrder(object? value, SequenceOrder fallback)
        {
            switch (value)
            {
                case null:
                    return fallback;
                case SequenceOrder order:
                    return order;
                case string s when Enum.TryParse<SequenceOrder>(s, true, out var parsed):
                    return parsed;
                case int i when Enum.IsDefined(typeof(SequenceOrder), i):
                    return (SequenceOrder)i;
                case long l when Enum.IsDefined(typeof(SequenceOrder), (int)l):
                    return (SequenceOrder)(int)l;
                case JsonElement jsonElement when jsonElement.ValueKind == JsonValueKind.String
                    && Enum.TryParse<SequenceOrder>(jsonElement.GetString(), true, out var jsonParsed):
                    return jsonParsed;
                case JsonElement jsonElement when jsonElement.ValueKind == JsonValueKind.Number
                    && jsonElement.TryGetInt32(out var jsonNumber)
                    && Enum.IsDefined(typeof(SequenceOrder), jsonNumber):
                    return (SequenceOrder)jsonNumber;
                default:
                    return fallback;
            }
        }

        private static List<double> CoerceToDoubleList(object? value)
        {
            var weights = new List<double>();
            if (value == null)
            {
                return weights;
            }

            if (value is JsonElement jsonElement)
            {
                if (jsonElement.ValueKind == JsonValueKind.Array)
                {
                    foreach (var item in jsonElement.EnumerateArray())
                    {
                        if (TryCoerceDouble(item, out var number))
                        {
                            weights.Add(number);
                        }
                    }
                    return weights;
                }
                if (TryCoerceDouble(jsonElement, out var singleNumber))
                {
                    weights.Add(singleNumber);
                    return weights;
                }
                if (jsonElement.ValueKind == JsonValueKind.String)
                {
                    return ParseWeightString(jsonElement.GetString());
                }
            }

            if (value is string stringValue)
            {
                return ParseWeightString(stringValue);
            }

            if (value is global::System.Collections.IEnumerable enumerable && value is not string)
            {
                foreach (var item in enumerable)
                {
                    if (TryCoerceDouble(item, out var number))
                    {
                        weights.Add(number);
                    }
                }
                return weights;
            }

            if (TryCoerceDouble(value, out var scalar))
            {
                weights.Add(scalar);
            }

            return weights;
        }

        private static bool TryCoerceDouble(object? value, out double number)
        {
            number = 0;
            switch (value)
            {
                case null:
                    return false;
                case int i:
                    number = i;
                    return true;
                case long l:
                    number = l;
                    return true;
                case short s:
                    number = s;
                    return true;
                case byte b:
                    number = b;
                    return true;
                case double d:
                    number = d;
                    return true;
                case float f:
                    number = f;
                    return true;
                case decimal m:
                    number = (double)m;
                    return true;
                case string s when double.TryParse(s, out var parsed):
                    number = parsed;
                    return true;
                case JsonElement jsonElement when jsonElement.ValueKind == JsonValueKind.Number && jsonElement.TryGetDouble(out var jsonNumber):
                    number = jsonNumber;
                    return true;
                case JsonElement jsonElement when jsonElement.ValueKind == JsonValueKind.String && double.TryParse(jsonElement.GetString(), out var jsonString):
                    number = jsonString;
                    return true;
                default:
                    return false;
            }
        }

        private static List<double> ParseWeightString(string? value)
        {
            if (string.IsNullOrWhiteSpace(value))
            {
                return new List<double>();
            }

            return value
                .Split(new[] { ',', ';' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(item => item.Trim())
                .Select(item => double.TryParse(item, out var parsed) ? parsed : 0d)
                .ToList();
        }

        private static int CoerceToInt(object? value, int fallback)
        {
            switch (value)
            {
                case null:
                    return fallback;
                case int i:
                    return i;
                case long l:
                    return (int)l;
                case short s:
                    return s;
                case byte b:
                    return b;
                case double d:
                    return (int)d;
                case float f:
                    return (int)f;
                case decimal m:
                    return (int)m;
                case bool b:
                    return b ? 1 : 0;
                case string s when int.TryParse(s, out var parsed):
                    return parsed;
                case JsonElement jsonElement:
                    if (jsonElement.ValueKind == JsonValueKind.Number && jsonElement.TryGetInt32(out var number))
                    {
                        return number;
                    }
                    if (jsonElement.ValueKind == JsonValueKind.String && int.TryParse(jsonElement.GetString(), out var strValue))
                    {
                        return strValue;
                    }
                    return fallback;
                default:
                    return fallback;
            }
        }

