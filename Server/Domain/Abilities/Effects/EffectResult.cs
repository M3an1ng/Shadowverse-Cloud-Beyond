using ShadowverseBeyond.Server.Domain.Entities;
// Removed duplicate using ShadowverseBeyond.Server.Domain.Entities;
using ShadowverseBeyond.Server.Domain.Abilities.Targets; // Added for TargetId
using ShadowverseBeyond.Server.Domain.Events; // Added for GameContext
using ShadowverseBeyond.Server.Domain.GameFlow.EffectQueue; // Added for EffectRequest
using System.Collections.Generic;
using System.Threading.Tasks;

namespace ShadowverseBeyond.Server.Domain.Abilities.Effects
{

    /// <summary>
    /// GameState动作结果
    /// </summary>
    public class GameStateActionResult
    {
        /// <summary>
        /// 是否成功
        /// </summary>
        public bool Success { get; set; } = true;

        /// <summary>
        /// 错误信息
        /// </summary>
        public string? ErrorMessage { get; set; } = string.Empty;

        /// <summary>
        /// 生成的事件列表 (强类型为 IGameEvent)
        /// </summary>
        public List<IGameEvent> GeneratedEvents { get; set; } = new(); // Changed type to List<IGameEvent>

        /// <summary>
        /// Optional: Before-intercept result used to rewrite or replace a triggering event.
        /// </summary>
        public EventInterceptResult? EventIntercept { get; set; }

        /// <summary>
        /// Resolved input parameters used by the effect handler.
        /// This is populated by <see cref="EffectExecutor"/> so callers can build
        /// follow-up events after generated events are fully processed.
        /// </summary>
        public IReadOnlyDictionary<string, object> ResolvedParameters { get; set; } = new Dictionary<string, object>();

        /// <summary>
        /// Resolved outputs computed from EffectConfig.Outputs.
        /// </summary>
        public IReadOnlyDictionary<string, object?> Outputs { get; set; } = new Dictionary<string, object?>();

        // EffectRequests property removed as per new architecture.
        // New effects are generated by Abilities via EventProcessor.

        /// <summary>
        /// 返回值（如果有）
        /// </summary>
        public object? ReturnValue { get; set; }

        /// <summary>
        /// 执行时间（毫秒）
        /// </summary>
        public long ExecutionTimeMs { get; set; } = 0;

        /// <summary>
        /// Optional: Detailed results for each target affected by the action.
        /// </summary>
        public List<DomainOperationResult> Results { get; set; } = new();
    }


    /// <summary>
    /// 效果执行结果
    /// </summary>
    public class EffectExecutionResult
    {
        /// <summary>
        /// 是否执行成功
        /// </summary>
        public bool Success { get; set; } = true;

        /// <summary>
        /// 执行的效果数量
        /// </summary>
        public int ExecutedEffectsCount { get; set; } = 0;

        /// <summary>
        /// 失败的效果数量
        /// </summary>
        public int FailedEffectsCount { get; set; } = 0;

        /// <summary>
        /// 错误信息
        /// </summary>
        public List<string> ErrorMessages { get; set; } = new();

        /// <summary>
        /// 生成的事件列表
        /// </summary>
        public List<IGameEvent> GeneratedEvents { get; set; } = new(); // Changed type to List<IGameEvent>

        /// <summary>
        /// 更新的变量
        /// </summary>
        public Dictionary<string, object> UpdatedVariables { get; set; } = new(); // Replaced AbilityVariables with Dictionary

        /// <summary>
        /// 执行时间（毫秒）
        /// </summary>
        public long ExecutionTimeMs { get; set; } = 0;
    }


    /// <summary>
    /// 领域操作的统一结果类型
    /// 【架构设计】区分原子操作和业务流程的返回类型
    /// </summary>
    public class DomainOperationResult
    {

        /// <summary>
        /// 【新架构】包含由效果计算产生的、待执行的“暂存事件”蓝图。
        /// 这个列表可以同时包含普通的“信号事件”和需要最终执行的“IExecutableEvent”。
        /// </summary>
        public List<IGameEvent> GeneratedEvents { get; set; } = new();

        // EffectRequests property removed as per new architecture.
        // New effects are generated by Abilities via EventProcessor.

        /// <summary>
        /// 操作是否成功
        /// </summary>
        public bool Success { get; set; } = true;

        /// <summary>
        /// 错误信息（如果操作失败）
        /// </summary>
        public string? ErrorMessage { get; set; }
    }
}
