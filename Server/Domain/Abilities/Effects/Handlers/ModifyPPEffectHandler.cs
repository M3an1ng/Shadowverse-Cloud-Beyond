using ShadowverseBeyond.Server.Domain.Abilities.Effects;
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers.Services;
using ShadowverseBeyond.Server.Domain.Abilities.Common;

namespace ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers
{
    /// <summary>
    /// Handles the effect of modifying a player's current Play Points (PP).
    /// </summary>
    public class ModifyPPEffectHandler : EffectHandlerBase<ModifyPPEffectParams>
    {
        private readonly ITargetProcessingService _targetProcessingService;

        public ModifyPPEffectHandler(ILogger<ModifyPPEffectHandler> logger, ITargetProcessingService targetProcessingService)
            : base(logger)
        {
            _targetProcessingService = targetProcessingService ?? throw new ArgumentNullException(nameof(targetProcessingService));
        }

        public override async Task<GameStateActionResult> ApplyAsync(GameContext context, ModifyPPEffectParams parameters)
        {
            const string effectName = "ModifyPPEffect";
            Logger.LogDebug("{EffectName}: Starting with ModifyAmount={Amount}.", effectName, parameters.ModifyAmount);

            Func<PlayerState, GameContext, Task<DomainOperationResult>> playerAction =
                (player, ctx) => // ModifyPlayPoints is synchronous
                {
                    var operationResult = player.ModifyPlayPoints(parameters.ModifyAmount);
                    return Task.FromResult(operationResult);
                };

            var serviceResult = await _targetProcessingService.ProcessTargetsAsync(
                context,
                playerAction,
                null,
                effectName);

            if (!serviceResult.Success && string.IsNullOrEmpty(serviceResult.ErrorMessage))
            {
                serviceResult.ErrorMessage = "Failed to process targets for modify PP effect, or no valid targets found.";
            }

            // The EffectCompletedEvent will be created by the EffectExecutor.
            // This handler is now only responsible for invoking the domain logic
            // and returning the atomic events generated by that logic.
            return serviceResult;
        }

        // CreateEffectCompletedEvent method is removed as this responsibility has moved to EffectExecutor.
    }
}