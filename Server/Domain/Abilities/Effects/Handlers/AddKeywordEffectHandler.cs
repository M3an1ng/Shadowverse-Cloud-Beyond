using AutoMapper;
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Bases;
using ShadowverseBeyond.Server.Domain.Abilities.Effects; // Add using for IMapper
using Microsoft.Extensions.Logging;
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers.Parameters;
using ShadowverseBeyond.Server.Domain.Entities;
using ShadowverseBeyond.Server.Domain.Events;
using ShadowverseBeyond.Server.Domain.Constants; // For CardKeyword
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers.Services;
using ShadowverseBeyond.Server.Domain.Abilities.Targets;

namespace ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers
{
    /// <summary>
    /// Handles the "AddKeyword" effect, generating events to indicate keyword additions to target cards.
    /// </summary>
    public class AddKeywordEffectHandler : EffectHandlerBase<AddKeywordEffectParams>
    {
        private readonly ITargetProcessingService _targetProcessingService;

        public AddKeywordEffectHandler(ILogger<AddKeywordEffectHandler> logger, ITargetProcessingService targetProcessingService)
            : base(logger)
        {
            _targetProcessingService = targetProcessingService ?? throw new ArgumentNullException(nameof(targetProcessingService));
        }

        public override GameStateActionResult Apply(GameContext context, AddKeywordEffectParams parameters)
        {
            const string effectName = "AddKeywordEffect";
            Logger.LogDebug("{EffectName}: Starting with Keyword={Keyword}.", effectName, parameters.Keyword);

            if (parameters.Keyword == CardKeyword.None)
            {
                Logger.LogWarning("{EffectName}: Keyword is None. No keyword will be added.", effectName);
                return new GameStateActionResult { Success = true }; // Not an error, just no action.
            }

            Func<CardInstance, GameContext, DomainOperationResult> cardAction =
                (card, ctx) => // AddKeywordAndCreateEvent is synchronous
                {
                    var operationResult = card.AddKeyword(parameters.Keyword);
                    return operationResult;
                };

            var serviceResult = _targetProcessingService.ProcessTargets(
                context,
                null,
                cardAction,
                effectName);

            if (!serviceResult.Success && string.IsNullOrEmpty(serviceResult.ErrorMessage))
            {
                serviceResult.ErrorMessage = "Failed to process targets for add keyword effect, or no valid targets found.";
            }

            // The EffectCompletedEvent will be created by the EffectExecutor.
            // This handler is now only responsible for invoking the domain logic
            // and returning the atomic events generated by that logic.
            return serviceResult;
        }

        // CreateEffectCompletedEvent method is removed as this responsibility has moved to EffectExecutor.
    }
}