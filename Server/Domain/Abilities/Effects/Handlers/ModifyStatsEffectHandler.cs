namespace ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers
{
    /// <summary>
    /// Handles the application of the ModifyStats effect.
    /// Targets CardInstances.
    /// </summary>
    public class ModifyStatsEffectHandler : EffectHandlerBase<ModifyStatsEffectParams>
    {
        private readonly ITargetProcessingService _targetProcessingService;

        public ModifyStatsEffectHandler(ILogger logger, ITargetProcessingService targetProcessingService)
            : base(logger) // Call base constructor with ILogger
        {
            _targetProcessingService = targetProcessingService ?? throw new ArgumentNullException(nameof(targetProcessingService));
        }

        /// <summary>
        /// Applies the ModifyStats effect to the selected card instance targets.
        /// </summary>
        public override async Task<GameStateActionResult> ApplyAsync(GameContext context, ModifyStatsEffectParams parameters)
        {
            const string effectName = "ModifyStatsEffect";

            // Define the action for modifying a CardInstance's stats
            Func<CardInstance, GameContext, Task<IndividualActionResult>> cardModifyAction =
                async (card, ctx) =>
                {
                    int originalAttack = card.CurrentAttack;
                    int originalHealth = card.CurrentHealth;
                    int originalMaxHealth = card.MaxHealth;
                    bool statsChanged = false;
                    var generatedEvents = new List<IGameEvent>(); // Events generated by this specific modification

                    Logger.LogTrace("{EffectName}: Applying to CardInstance {InstanceId}. Original Stats: A={Atk}, H={Hp}/{MaxHp}",
                                     effectName, card.InstanceId, originalAttack, originalHealth, originalMaxHealth);

                    // Apply MaxHealth modifier first
                    if (parameters.MaxHealthModifier.HasValue && parameters.MaxHealthModifier.Value != 0)
                    {
                        int modifier = parameters.MaxHealthModifier.Value;
                        card.MaxHealth = Math.Max(1, card.MaxHealth + modifier); // Ensure MaxHealth doesn't go below 1
                        // If MaxHealth increased, increase CurrentHealth by the same amount
                        if (modifier > 0)
                        {
                            card.CurrentHealth += modifier;
                        }
                        // If MaxHealth decreased, cap CurrentHealth
                        else
                        {
                            card.CurrentHealth = Math.Min(card.CurrentHealth, card.MaxHealth);
                        }
                        statsChanged = true;
                        Logger.LogTrace("{EffectName}: Modified MaxHealth by {Mod}. New: {NewMaxHp}. CurrentHealth adjusted to: {NewHp}",
                                         effectName, modifier, card.MaxHealth, card.CurrentHealth);
                    }

                    // Apply Attack modifier
                    if (parameters.AttackModifier.HasValue && parameters.AttackModifier.Value != 0)
                    {
                        // Attack can go below zero (though often displayed as 0)
                        card.CurrentAttack += parameters.AttackModifier.Value;
                        statsChanged = true;
                        Logger.LogTrace("{EffectName}: Modified Attack by {Mod}. New: {NewAtk}",
                                        effectName, parameters.AttackModifier.Value, card.CurrentAttack);
                    }

                    // Apply Health modifier (after MaxHealth adjustment)
                    if (parameters.HealthModifier.HasValue && parameters.HealthModifier.Value != 0)
                    {
                        // Apply modifier but clamp between 1 and new MaxHealth
                        card.CurrentHealth = Math.Max(1, Math.Min(card.CurrentHealth + parameters.HealthModifier.Value, card.MaxHealth));
                        statsChanged = true;
                        Logger.LogTrace("{EffectName}: Modified Health by {Mod}. New: {NewHp}/{NewMaxHp}",
                                         effectName, parameters.HealthModifier.Value, card.CurrentHealth, card.MaxHealth);
                    }

                    // Check for death after all modifications
                    if (card.CurrentHealth <= 0)
                    {
                        Logger.LogInformation("{EffectName}: CardInstance {InstanceId} health reached 0 or below ({CurrentHealth}). Triggering destruction.",
                                             effectName, card.InstanceId, card.CurrentHealth);
                        // Generate CardDestroyedEvent
                        // Need PlayerStateDto for the event constructor
                        var ownerPlayer = ctx.CurrentGameState.GetPlayerState(card.OwnerPlayerId);
                        if (ownerPlayer != null)
                        {
                            // Assuming GameContext has access to IMapper or we inject it here
                            // For now, let's assume GameService handles the mapping later based on PlayerId
                            // generatedEvents.Add(new CardDestroyedEvent(ownerPlayerDto, card)); 
                            // TODO: Refine event generation - maybe return a flag or specific result?
                            // For now, the StatChangeEvent will reflect health <= 0
                        }
                        else
                        {
                            Logger.LogError("{EffectName}: Could not find owner PlayerState {PlayerId} for destroyed card {InstanceId}.",
                                            effectName, card.OwnerPlayerId, card.InstanceId);
                        }
                    }

                    // Generate StatChangeEvent if stats actually changed
                    if (statsChanged)
                    {
                        // Assuming StatChangeEventDto exists and takes relevant parameters
                        // Need PlayerId of the controller of the ability source for the event
                        var sourcePlayerId = ctx.RequestingPlayerId; // Or ctx.SourceCard.OwnerPlayerId? Needs clarification. Let's use RequestingPlayerId for now.
                        // Use the correct domain event: StatChangedEvent, passing the InstanceId
                        generatedEvents.Add(new StatChangedEvent(sourcePlayerId, card.InstanceId, card.CurrentAttack, card.CurrentHealth, card.MaxHealth));
                        Logger.LogDebug("{EffectName}: Stats changed for {InstanceId}. New Stats: A={Atk}, H={Hp}/{MaxHp}. Event generated.",
                                        effectName, card.InstanceId, card.CurrentAttack, card.CurrentHealth, card.MaxHealth);
                    }

                    await Task.CompletedTask; // Modifications are synchronous

                    return new IndividualActionResult
                    {
                        TargetId = TargetId.Card(card.InstanceId),
                        Success = true,
                        Message = statsChanged ? $"Stats modified. New: A={card.CurrentAttack}, H={card.CurrentHealth}/{card.MaxHealth}" : "No stats changed.",
                        GeneratedEvents = generatedEvents // Include events generated by this specific modification
                    };
                };

            // Call the target processing service, expecting CardInstance targets
            return await _targetProcessingService.ProcessTargetsAsync(
                context,
                TargetIdType.CardInstance,
                null, // No Player action
                cardModifyAction,
                effectName);
        }
    }
}