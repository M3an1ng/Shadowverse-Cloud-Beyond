using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using Microsoft.Extensions.Logging;
using ShadowverseBeyond.Server.Domain.Entities;
using ShadowverseBeyond.Server.Domain.Events;
using ShadowverseBeyond.Server.Domain.Abilities.Targets; // For TargetId, TargetIdType
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers.Parameters; // For DamageEffectParams
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Bases; // Added for EffectHandlerBase
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers.Services; // For ITargetProcessingService
using ShadowverseBeyond.Server.Domain.Abilities.Effects;

namespace ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers
{
    /// <summary>
    /// Handles the application of the Damage effect.
    /// </summary>
    // Inherit from EffectHandlerBase instead of IEffectHandler directly
    public class DamageEffectHandler : EffectHandlerBase<DamageEffectParams>
    {
        // Remove private _logger, use base.Logger or Logger directly
        private readonly ITargetProcessingService _targetProcessingService; // Inject the service

        // Adjust constructor signature to accept ILogger and call base(logger) correctly
        public DamageEffectHandler(ILogger logger, ITargetProcessingService targetProcessingService) // Changed ILogger<T> to ILogger
            : base(logger) // Call base constructor with ILogger
        {
            _targetProcessingService = targetProcessingService ?? throw new ArgumentNullException(nameof(targetProcessingService)); // Store injected service
        }

        /// <summary>
        /// Applies damage to the selected targets based on the provided parameters.
        /// </summary>
        // Add override keyword
        public override async Task<GameStateActionResult> ApplyAsync(GameContext context, DamageEffectParams parameters)
        {
            const string effectName = "DamageEffect"; // Consistent name for logging
            // Use protected Logger directly
            Logger.LogDebug("Executing {EffectName} with DamageAmount: {Amount} for source card {SourceCardId}",
                             effectName, parameters.DamageAmount, context.SourceCard?.InstanceId);

            // Define the action to perform on each valid CardInstance target
            Func<CardInstance, GameContext, Task<IndividualActionResult>> cardDamageAction =
                async (card, ctx) =>
                {
                    // Use protected Logger directly
                    Logger.LogDebug("{EffectName}: Applying damage {DamageAmount} to CardInstance {InstanceId}",
                                     effectName, parameters.DamageAmount, card.InstanceId);

                    // Call the TakeDamage method on the CardInstance
                    // Capture the events generated by TakeDamage
                    var generatedEvents = card.TakeDamage(parameters.DamageAmount, ctx.SourceCard);

                    // No need for Task.CompletedTask here as TakeDamage is synchronous

                    // Return the result including the generated events
                    return new IndividualActionResult
                    {
                        TargetId = TargetId.Card(card.InstanceId), // Use TargetId factory
                        Success = true,
                        Message = $"Applied {parameters.DamageAmount} damage.",
                        GeneratedEvents = generatedEvents // Include the generated events
                    };
                };

            // Call the injected service to handle target processing
            return await _targetProcessingService.ProcessTargetsAsync(context, TargetIdType.CardInstance, null, cardDamageAction, effectName);
        }

        // Internal helper method ApplyEffectToTargetsInternalAsync has been removed.
    }
}