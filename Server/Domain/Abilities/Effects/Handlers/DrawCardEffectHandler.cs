using System;
using Microsoft.Extensions.Logging;
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Bases;
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers.Parameters;
using ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers.Services;
using ShadowverseBeyond.Server.Domain.Abilities.Targets;
using ShadowverseBeyond.Server.Domain.Entities;
using ShadowverseBeyond.Server.Domain.Events;

namespace ShadowverseBeyond.Server.Domain.Abilities.Effects.Handlers
{
    /// <summary>
    /// 【最终重构】处理“DrawCard”效果。
    /// 遵循标准架构，使用 ITargetProcessingService 对每个目标玩家执行抽牌操作。
    /// </summary>
    public class DrawCardEffectHandler : EffectHandlerBase<DrawCardEffectParams>
    {
        private readonly ITargetProcessingService _targetProcessingService;

        public DrawCardEffectHandler(
            ILogger<DrawCardEffectHandler> logger,
            ITargetProcessingService targetProcessingService)
            : base(logger)
        {
            _targetProcessingService = targetProcessingService ?? throw new ArgumentNullException(nameof(targetProcessingService));
        }

        public override async Task<GameStateActionResult> ApplyAsync(GameContext context, DrawCardEffectParams parameters)
        {
            const string effectName = "DrawCardEffect";
            Logger.LogDebug("{EffectName}: Starting with DrawAmount={Amount}.", effectName, parameters.DrawAmount);

            if (parameters.DrawAmount <= 0)
            {
                Logger.LogWarning("{EffectName}: DrawAmount is {DrawAmount}, no cards will be drawn.", effectName, parameters.DrawAmount);
                return new GameStateActionResult { Success = false, ErrorMessage = "DrawAmount must be positive." };
            }

            Func<PlayerState, GameContext, Task<DomainOperationResult>> playerDrawAction =
                (player, ctx) =>
                {
                    var drawResult = player.DrawCards(parameters.DrawAmount); // This is now a synchronous method in PlayerState
                    Logger.LogInformation("{EffectName}: Player {PlayerId} processed card draw. Events: {EventCount}",
                        effectName, player.PlayerId, drawResult.GeneratedEvents.Count);
                    return Task.FromResult(drawResult); // Wrap synchronous result in a Task for the service
                };

            // ITargetProcessingService is expected to aggregate events and requests from DomainOperationResults
            // into the GeneratedEvents and EffectRequests of the GameStateActionResult it returns.
            var serviceResult = await _targetProcessingService.ProcessTargetsAsync(
                context,
                playerDrawAction,
                null,
                effectName);

            // If serviceResult failed, return it directly.
            if (!serviceResult.Success)
            {
                return serviceResult;
            }

            // The EffectCompletedEvent will be created by the EffectExecutor.
            // This handler is now only responsible for invoking the domain logic
            // and returning the atomic events generated by that logic.
            return serviceResult;
        }

        // CreateEffectCompletedEvent method is removed as this responsibility has moved to EffectExecutor.
    }
}